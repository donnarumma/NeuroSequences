function data_trials = build_mushiake_trial_data(MDP, trialIndex, pms)
%BUILD_MUSHIAKE_TRIAL_DATA Reconstruct one or more Mushiake data_trials entries.

if nargin < 3 || isempty(pms)
    pms = default_mushiake_collect_params();
else
    pms = default_mushiake_collect_params(pms);
end

if iscell(MDP)
    mushiakeMDP = MDP{1};
else
    mushiakeMDP = MDP;
end

MDP_Low = mushiakeMDP.mdp;

if pms.useSingleStepRecognitionLevel
    [popFR, tPopFR, labEpochs] = single_step_mushiake_to_firing_rates(mushiakeMDP, pms);
elseif strcmpi(pms.firingRateMode, 'legacy_hai')
    [popFR, tPopFR, labEpochs] = HAI_MDPtoFiringRates(MDP_Low, pms.iFactor, pms.dt);
else
    [popFR, tPopFR, labEpochs] = mushiake_MDPtoFiringRates( ...
        MDP_Low, pms.iFactor, pms.dt, pms.firingRateMode, ...
        pms.policySharpness, pms.policyWeightSource, pms.policyTimeWeightPower);
end
nPops = size(popFR, 1);
nBins = sum(labEpochs == 1);

if pms.addFlatPrior
    flatPriorLevel = pms.flatPriorLevel;
    if isempty(flatPriorLevel)
        flatPriorLevel = 1 / nPops;
    end
    popFR = [ones(nPops, nBins) * flatPriorLevel, popFR];
end

if pms.smoothWindow > 1
    for iPop = 1:nPops
        popFR(iPop, :) = smooth(popFR(iPop, :), pms.smoothWindow);
    end
end

if pms.addFlatPrior
    btime = tPopFR(end) + (1:nBins) * mean(diff(tPopFR));
    tPopFR = [tPopFR, btime];
    labEpochs = [zeros(1, nBins), labEpochs];
end

tPopFR = tPopFR / tPopFR(end);
trialName = [pms.actions{MDP_Low.s(2, 2:end)}];

goalState = NaN;
if isfield(MDP_Low, 'C') && numel(MDP_Low.C) >= 1 && ~isempty(MDP_Low.C{1})
    [~, goalState] = max(MDP_Low.C{1}(:, 1));
end

baseTrial = struct();
baseTrial.popFR = popFR;
baseTrial.tPopFR = tPopFR;
baseTrial.labEpochs = labEpochs;
baseTrial.trialName = trialName;
baseTrial.trialLabel = trialName;
if pms.useSingleStepRecognitionLevel
    baseTrial.signalMode = 'preprocessedPopFR_singleStepRecognition';
else
    baseTrial.signalMode = 'preprocessedPopFR';
end
baseTrial.iMushiake = mushiakeMDP.iMushiake;
baseTrial.goalState = goalState;
baseTrial.sourceTrialIndex = trialIndex;

nReplications = max(1, round(pms.trialReplications));
data_trials = repmat(baseTrial, nReplications, 1);
for iReplication = 1:nReplications
    data_trials(iReplication).replicateIndex = iReplication;
end
end

function pms = default_mushiake_collect_params(parSource)
% Default preprocessing parameters for collected Mushiake trials.

pms.iFactor = 2;
pms.dt = 1 / 64;
pms.actions = {'U', 'D', 'L', 'R', 'S'};
pms.addFlatPrior = true;
pms.flatPriorLevel = [];
pms.smoothWindow = 8;
pms.trialReplications = 1;
pms.firingRateMode = 'stacked'; % Full xn stacking by default; MAIN_Mushiake can override for diagnostics.
pms.policySharpness = 1; % Exponent applied to policy weights for committed-average diagnostics.
pms.policyWeightSource = 'final'; % Which policy posterior to freeze: first, mean, final, or a numeric column index.
pms.policyTimeWeightPower = 0; % When policyWeightSource is mean, bias the average toward later columns of R.
pms.useSingleStepRecognitionLevel = false; % If true, concatenate the one-step nested Mushiake mdp sequence instead of the solved outer low-level xn.

if nargin < 1 || isempty(parSource)
    return;
end

fieldNames = fieldnames(parSource);
for fieldIndex = 1:numel(fieldNames)
    pms.(fieldNames{fieldIndex}) = parSource.(fieldNames{fieldIndex});
end

end

function [popFR, tPopFR, labEpochs] = single_step_mushiake_to_firing_rates(mushiakeMDP, pms)
% Concatenate the firing rates generated by the nested one-step recognition MDPs.

innerMdps = resolve_single_step_mushiake_mdps(mushiakeMDP);
if isempty(innerMdps)
    error('%s:MissingSingleStepRecognition', mfilename, ...
        ['useSingleStepRecognitionLevel is enabled, but no nested one-step ' ...
         'Mushiake mdp sequence was found under MDP.mdp(1).mdp.']);
end

nEpochs = numel(innerMdps);
popFR = [];
labEpochs = [];

for iEpoch = 1:nEpochs
    currentMdp = innerMdps(iEpoch);
    if strcmpi(pms.firingRateMode, 'legacy_hai')
        [curFR, ~, curLabEpochs] = HAI_MDPtoFiringRates(currentMdp, pms.iFactor, pms.dt);
    else
        [curFR, ~, curLabEpochs] = mushiake_MDPtoFiringRates( ...
            currentMdp, pms.iFactor, pms.dt, pms.firingRateMode, ...
            pms.policySharpness, pms.policyWeightSource, pms.policyTimeWeightPower);
    end

    if isempty(popFR)
        popFR = curFR;
    else
        if size(curFR, 1) ~= size(popFR, 1)
            error('%s:InconsistentSingleStepRows', mfilename, ...
                ['Nested one-step MDP %d returned %d populations, expected %d.'], ...
                iEpoch, size(curFR, 1), size(popFR, 1));
        end
        popFR = [popFR, curFR]; %#ok<AGROW>
    end

    labEpochs = [labEpochs, curLabEpochs + (iEpoch - 1)]; %#ok<AGROW>
end

tPopFR = (1:size(popFR, 2)) * pms.dt;
end

function innerMdps = resolve_single_step_mushiake_mdps(mushiakeMDP)
% Locate the nested one-step recognition sequence added under the low level.

innerMdps = struct([]);

if ~isstruct(mushiakeMDP) || ~isfield(mushiakeMDP, 'mdp') || isempty(mushiakeMDP.mdp)
    return;
end

if isfield(mushiakeMDP.mdp(1), 'mdp') && ~isempty(mushiakeMDP.mdp(1).mdp)
    innerMdps = mushiakeMDP.mdp(1).mdp;
end
end
