function description = build_sensor_trial_description(pms)
%BUILD_SENSOR_TRIAL_DESCRIPTION Build the canonical sensor trial descriptor.

description = sprintf('%s%g_nT%gnS%gsRg%gH%g', ...
    pms.namefor, ...
    pms.iTrial, ...
    pms.nGoToTargets, ...
    pms.nSteps, ...
    pms.irng, ...
    pms.nHiddenFactors);
end
